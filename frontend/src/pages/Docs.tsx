function Highlighted(props: { text: string; words: string[] }) {
  return (
    <For each={highlightParts(props.text, props.words)}>
      {(part) =>
        part.hit ? (
          <mark class="rounded-sm bg-amber-bg text-amber-ink">{part.text}</mark>
        ) : (
          part.text
        )
      }
    </For>
  );
}

function Paragraphs(props: { text: string; class?: string }) {
  return (
    <For each={props.text.split(/\n{2,}/)}>
      {(paragraph) => <p class={`whitespace-pre-line ${props.class ?? ""}`}>{paragraph}</p>}
    </For>
  );
}

