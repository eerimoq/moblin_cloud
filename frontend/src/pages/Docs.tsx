export default function Docs() {
  const [route, setRoute] = createSignal<Route>(hashToRoute(location.hash));
  const [menuOpen, setMenuOpen] = createSignal(false);
  let input: HTMLInputElement | undefined;
  let main: HTMLDivElement | undefined;

  const query = () => {
    const current = route();
    return current.kind === "search" ? current.query : "";
  };
  const setQuery = (text: string) => {
    const searching = route().kind === "search";
    const next: Route = text ? { kind: "search", query: text } : { kind: "home" };
    const url = text ? routeToHash(next) : location.pathname;
    if (searching) {
      history.replaceState(null, "", url);
    } else if (text) {
      history.pushState(null, "", url);
    } else {
      return;
    }
    setRoute(next);
  };
  const onHashChange = () => {
    setRoute(hashToRoute(location.hash));
    setMenuOpen(false);
  };
  const onKeyDown = (event: KeyboardEvent) => {
    const target = event.target as HTMLElement;
    const typing = target.closest("input, textarea, [contenteditable]") !== null;
    if (event.key === "/" && !typing) {
      event.preventDefault();
      input?.focus();
    } else if (event.key === "Escape" && target === input) {
      setQuery("");
    }
  };
  onMount(() => {
    window.addEventListener("hashchange", onHashChange);
    window.addEventListener("keydown", onKeyDown);
  });
  onCleanup(() => {
    window.removeEventListener("hashchange", onHashChange);
    window.removeEventListener("keydown", onKeyDown);
  });

  const title = () => {
    const current = route();
    if (current.kind === "guide") {
      return guidesById.get(current.id)?.title;
    }
    if (current.kind === "settings") {
      return settingsPages.get(current.id)?.path.join(" › ");
    }
    if (current.kind === "search") {
      return t("Search for “{query}”", { query: current.query });
    }
    return undefined;
  };

  createEffect(() => {
    document.title = title()
      ? t("{title} – Moblin docs", { title: title()! })
      : t("Documentation – Moblin");
  });

  createEffect(
    on(route, (current) => {
      requestAnimationFrame(() => {
        if (current.kind === "search") {
          const scroll = (history.state as { scroll?: number } | null)?.scroll;
          if (scroll !== undefined) {
            window.scrollTo(0, scroll);
          }
          return;
        }
        const anchor = current.kind === "home" ? undefined : current.anchor;
        const element = anchor ? document.getElementById(anchor) : null;
        if (element) {
          element.scrollIntoView({ block: "center" });
          element.classList.remove("docs-flash");
          void element.offsetWidth;
          element.classList.add("docs-flash");
        } else if (main && main.getBoundingClientRect().top < 0) {
          main.scrollIntoView();
        }
      });
    }),
  );

  return (
    <>
      <Nav />
      <main>
        <section class="border-b border-line/40 bg-band">
          <div class="mx-auto flex max-w-[1120px] flex-col gap-5 px-5 pt-10 pb-8 sm:px-8 lg:pt-14">
            <div class="flex flex-col gap-2">
              <span class="font-display text-[15px] font-semibold uppercase tracking-[0.08em] text-leaf">
                {t("Documentation")}
              </span>
              <h1 class="text-[36px] leading-[1.05] font-bold text-balance sm:text-5xl">
                {t("How to use Moblin")}
              </h1>
              <p class="max-w-[640px] text-lg text-ink-2 text-pretty">
                {t("Step-by-step guides and every setting in the app, searchable in one place.")}
              </p>
            </div>
            <AiNotice />
            <SearchBox query={query()} onInput={setQuery} ref={(element) => (input = element)} />
          </div>
        </section>
        <div
          ref={(element) => (main = element)}
          class="mx-auto max-w-[1120px] scroll-mt-16 px-5 py-8 sm:px-8 lg:grid lg:scroll-mt-18 lg:grid-cols-[250px_minmax(0,1fr)] lg:gap-10 lg:py-12"
        >
          <div class="mb-6 lg:hidden">
            <button
              type="button"
              class="flex w-full items-center justify-between rounded-2xl border-[1.5px] border-line bg-card px-5 py-3 font-bold"
              aria-expanded={menuOpen()}
              onClick={() => setMenuOpen(!menuOpen())}
            >
              {t("Browse guides and settings")}
              <Icon name={menuOpen() ? "close" : "menu"} class="size-5" />
            </button>
            <Show when={menuOpen()}>
              <div class="mt-3 rounded-2xl border-[1.5px] border-line bg-card p-3">
                <Sidebar route={route()} />
              </div>
            </Show>
          </div>
          <aside class="hidden lg:block">
            <div class="sticky top-[calc(4.5rem+24px)] max-h-[calc(100vh-4.5rem-48px)] overflow-y-auto pr-2 pb-8">
              <Sidebar route={route()} />
            </div>
          </aside>
          <div class="min-w-0">
            <Show when={!query()} fallback={<SearchResults query={query()} />}>
              <Switch fallback={<NotFound />}>
                <Match when={route().kind === "home"}>
                  <Overview />
                </Match>
                <Match
                  when={(() => {
                    const current = route();
                    return current.kind === "guide" ? guidesById.get(current.id) : undefined;
                  })()}
                >
                  {(guide) => <GuideView guide={guide()} />}
                </Match>
                <Match
                  when={(() => {
                    const current = route();
                    return current.kind === "settings" ? settingsPages.get(current.id) : undefined;
                  })()}
                >
                  {(page) => <SettingsPageView page={page()} />}
                </Match>
              </Switch>
            </Show>
          </div>
        </div>
      </main>
      <Footer />
    </>
  );
}
