function TreeNode(props: { page: SettingsPage; current?: SettingsPage }) {
  const children = createMemo(() => childPages(props.page));
  const isCurrent = () => props.current?.id === props.page.id;
  const containsCurrent = () =>
    props.current !== undefined &&
    ancestors(props.current).some((ancestor) => ancestor.id === props.page.id);
  const [open, setOpen] = createSignal(false);
  createEffect(() => {
    if (containsCurrent()) {
      setOpen(true);
    }
  });
  return (
    <li>
      <div class="flex items-center">
        <Show
          when={children().length > 0}
          fallback={<span class="size-7 shrink-0" aria-hidden="true" />}
        >
          <button
            type="button"
            class="flex size-7 shrink-0 items-center justify-center rounded-md text-muted hover:bg-ghost hover:text-ink"
            aria-label={
              open()
                ? t("Collapse {page}", { page: props.page.title })
                : t("Expand {page}", { page: props.page.title })
            }
            aria-expanded={open()}
            onClick={() => setOpen(!open())}
          >
            <svg
              viewBox="0 0 24 24"
              class={`size-4 transition-transform ${open() ? "rotate-90" : ""}`}
              fill="none"
              stroke="currentColor"
              stroke-width="2.5"
              stroke-linecap="round"
              stroke-linejoin="round"
              aria-hidden="true"
            >
              <path d="m9 6 6 6-6 6" />
            </svg>
          </button>
        </Show>
        <a
          href={routeToHash({ kind: "settings", id: props.page.id })}
          class={`min-w-0 flex-1 truncate rounded-lg px-2 py-1 text-[15px] ${
            isCurrent()
              ? "bg-ghost font-bold text-leaf"
              : "text-ink-2 hover:bg-ghost hover:text-ink"
          }`}
          aria-current={isCurrent() ? "page" : undefined}
          title={props.page.title}
        >
          {props.page.title}
        </a>
      </div>
      <Show when={open() && children().length > 0}>
        <ul class="ml-3.5 border-l border-line pl-1">
          <For each={children()}>
            {(child) => <TreeNode page={child} current={props.current} />}
          </For>
        </ul>
      </Show>
    </li>
  );
}

